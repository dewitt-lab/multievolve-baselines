#!/usr/bin/env python
"""
Train MULTI-evolve FCN ensemble and score all combinatorial variants.

Run from the project root with the multievolve conda environment:
    conda activate multievolve
    python analysis/run_multievolve.py apex
    python analysis/run_multievolve.py dcasrx
    python analysis/run_multievolve.py huabc2 --measurement expr
    python analysis/run_multievolve.py huabc2 --measurement bind

Prerequisites (generated by analysis/prep_training_data.py):
    output/{protein}/{protein}_training_log2.csv
    output/{protein}/combo_muts.csv
    For single-chain: data/{protein}.fasta
    For HuABC2: data/huabc2_vh.fasta, data/huabc2_vl.fasta

Output:
    output/{protein}/{protein}[_{measurement}]_multievolve_proposals.csv
    Columns: Mutations, Full_Sequence, Mut_string, num_muts, <fold_0..9>, average
"""
import os
import sys

# Disable wandb (pulled in by MULTI-evolve internals but not used here)
os.environ['WANDB_MODE'] = 'disabled'

REPO = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'MULTI-evolve')
sys.path.insert(0, REPO)

import pandas as pd
from Bio import SeqIO

from multievolve.splitters import KFoldProteinSplitter
from multievolve.featurizers import OneHotFeaturizer
from multievolve.predictors import Fcn
from multievolve.proposers import CombinatorialProposer

import argparse


if __name__ == '__main__':
    # Required on macOS: multiprocessing uses 'spawn' so all executable code
    # must be inside this guard to prevent infinite re-execution of the script.
    parser = argparse.ArgumentParser()
    parser.add_argument('protein', type=str, choices=['apex', 'dcasrx', 'huabc2'])
    parser.add_argument('--zerolayer', action='store_true', help="Use 0-layer NN (instead of default architecture)")
    parser.add_argument('--measurement', type=str, default=None,
                        choices=['expr', 'bind'],
                        help='Measurement type (required for huabc2)')
    args = parser.parse_args()

    if args.protein == 'huabc2' and args.measurement is None:
        parser.error('--measurement is required for huabc2')

    if args.protein == 'apex':
        if not args.zerolayer:
            # ---- Architecture ----
            CONFIG = {
                'layer_size': 100,
                'num_layers': 5,
                'learning_rate': 0.001,
                'batch_size': 16,
                'optimizer': 'adam',
                'epochs': 300,
            }
        else:
            
            # ---- Architecture ----
            CONFIG = {
                'layer_size': 100,
                'num_layers': 0,
                'learning_rate': 0.001,
                'batch_size': 32,
                'optimizer': 'adam',
                'epochs': 300,
            }

    elif args.protein == 'dcasrx':
        if not args.zerolayer:
            # ---- Architecture ----
            CONFIG = {
                'layer_size': 100,
                'num_layers': 1,
                'learning_rate': 0.001,
                'batch_size': 32,
                'optimizer': 'adam',
                'epochs': 300,
            }

        else:
            # ---- Architecture ----
            CONFIG = {
                'layer_size': 100,
                'num_layers': 0,
                'learning_rate': 0.0001,
                'batch_size': 8,
                'optimizer': 'adam',
                'epochs': 300,
            }

    elif args.protein == 'huabc2':
        if not args.zerolayer:
            if args.measurement == 'expr':
                CONFIG = {
                    'layer_size': 100,
                    'num_layers': 5,
                    'learning_rate': 0.0001,
                    'batch_size': 4,
                    'optimizer': 'adam',
                    'epochs': 300,
                }
            elif args.measurement == 'bind':
                CONFIG = {
                    'layer_size': 100,
                    'num_layers': 3,
                    'learning_rate': 0.0001,
                    'batch_size': 4,
                    'optimizer': 'adam',
                'epochs': 300,
                }
        else:
            if args.measurement == 'expr':
                CONFIG = {
                    'layer_size': 100,
                    'num_layers': 0,
                    'learning_rate': 0.001,
                    'batch_size': 16,
                    'optimizer': 'adam',
                    'epochs': 300,
                }
            elif args.measurement == 'bind':
                CONFIG = {
                    'layer_size': 100,
                    'num_layers': 0,
                    'learning_rate': 0.0001,
                    'batch_size': 4,
                    'optimizer': 'adam',
                    'epochs': 300,
                }

    # ---- Paths ----
    ANALYSIS_DIR = os.path.dirname(os.path.abspath(__file__))
    ROOT_DIR     = os.path.dirname(ANALYSIS_DIR)
    # Training data written by prep_training_data.py
    PROTEINS_DIR = os.path.join(ROOT_DIR, 'output', args.protein)

    meas_tag = f'_{args.measurement}' if args.measurement else ''

    if args.protein == 'huabc2':
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'huabc2_training_{args.measurement}_log2.csv')
        # Multi-chain: pass list of FASTA files (VH, VL)
        DATA_DIR = os.path.join(ROOT_DIR, 'data')
        WT_FASTA = [
            os.path.join(DATA_DIR, 'huabc2_vh.fasta'),
            os.path.join(DATA_DIR, 'huabc2_vl.fasta'),
        ]
        IS_MULTICHAIN = True
    else:
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'{args.protein}_training_log2.csv')
        WT_FASTA     = os.path.join(ROOT_DIR, 'data', f'{args.protein}.fasta')
        IS_MULTICHAIN = False

    layer_tag = '_0layer' if args.zerolayer else ''
    OUTPUT_CSV = os.path.join(
        PROTEINS_DIR, f'{args.protein}{meas_tag}{layer_tag}_multievolve_proposals.csv')
    COMBO_CSV  = os.path.join(PROTEINS_DIR, 'combo_muts.csv')

    # KFoldProteinSplitter resolves paths relative to the MULTI-evolve repo root
    # So wt_file and data must be absolute paths
    paths_to_check = [TRAINING_CSV, COMBO_CSV]
    if IS_MULTICHAIN:
        paths_to_check.extend(WT_FASTA)
    else:
        paths_to_check.append(WT_FASTA)
    for path in paths_to_check:
        if not os.path.exists(path):
            raise FileNotFoundError(
                f"Missing: {path}\n"
                "Run: python analysis/prep_training_data.py "
                f"{args.protein}"
            )

    # ---- K-fold splits ----
    print("Generating 10-fold splits...")
    splitter = KFoldProteinSplitter(
        args.protein,
        TRAINING_CSV,
        WT_FASTA,
        csv_has_header=True,
        use_cache=True,
        y_scaling=True,
        val_split=0.15,
    )
    splits = splitter.generate_splits(n_splits=10)
    print(f"  Training set size: {len(splitter.data)} variants")

    # ---- Train 10 FCN models ----
    print("Training 10 FCN models (one per fold)...")
    featurizer = OneHotFeaturizer(protein=args.protein, use_cache=True)
    models = []
    for i, split in enumerate(splits):
        print(f"  Fold {i+1}/10...", flush=True)
        model = Fcn(split, featurizer, config=CONFIG, use_cache=True, show_plots=False)
        model.run_model()
        models.append(model)
    print("Training complete.")

    # ---- Load WT sequence and mutation pool ----
    if IS_MULTICHAIN:
        # Concatenate chain sequences
        chain_seqs = []
        for fasta_path in WT_FASTA:
            chain_seqs.append(str(SeqIO.read(fasta_path, 'fasta').seq.upper()))
        wt_seq = ''.join(chain_seqs)
        chain_lengths = [len(s) for s in chain_seqs]
        print(f"Multi-chain WT: {' + '.join(str(l) for l in chain_lengths)} "
              f"= {len(wt_seq)} AA")

        # Convert chain-notation combo_muts (e.g. 'L11Q:WT', 'WT:F82G')
        # to flat format with VL positions offset by VH chain length.
        # This matches what _shift_mutation_position() does for training data.
        raw_muts = pd.read_csv(COMBO_CSV, header=None)[0].tolist()
        mutation_pool = []
        for entry in raw_muts:
            parts = entry.split(':')
            # Chain 1 (VH) mutations — positions unchanged
            for m in parts[0].split('/'):
                if m != 'WT':
                    mutation_pool.append(m)
            # Chain 2 (VL) mutations — offset positions by chain 1 length
            for m in parts[1].split('/'):
                if m != 'WT':
                    wt_aa = m[0]
                    pos = int(m[1:-1])
                    mut_aa = m[-1]
                    offset_pos = pos + chain_lengths[0]
                    mutation_pool.append(f'{wt_aa}{offset_pos}{mut_aa}')
    else:
        wt_seq = str(SeqIO.read(WT_FASTA, 'fasta').seq.upper())
        mutation_pool = pd.read_csv(COMBO_CSV, header=None).values.flatten().tolist()

    print(f"Mutation pool: {len(mutation_pool)} mutations — {mutation_pool}")

    # ---- Generate and score all combinatorial variants ----
    # trust_radius=9 generates r=2..9 mutations
    # num_seeds=-1 enumerates all combinations
    print("Generating all combinatorial proposals (trust_radius=9)...")
    proposer = CombinatorialProposer(
        start_seq=wt_seq,
        models=models,
        trust_radius=9,
        num_seeds=-1,
        mutation_pool=mutation_pool,
    )
    proposer.propose(output_df=False)
    print(f"  Generated {len(proposer.proposals)} combinatorial variants")

    print("Scoring with ensemble models...")
    proposer.evaluate_proposals()

    print(f"\nTotal proposals scored: {len(proposer.proposals)}")
    print(proposer.proposals[['Mut_string', 'num_muts', 'average']].head(10))

    proposer.proposals.to_csv(OUTPUT_CSV, index=False)
    print(f"\nSaved to {OUTPUT_CSV}")
