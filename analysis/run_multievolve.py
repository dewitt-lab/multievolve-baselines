#!/usr/bin/env python
"""
Train MULTI-evolve FCN ensemble and score all combinatorial variants.

Run from the project root with the multievolve conda environment:
    conda activate multievolve
    python analysis/run_multievolve.py apex
    python analysis/run_multievolve.py dcasrx
    python analysis/run_multievolve.py huabc2 --measurement expr
    python analysis/run_multievolve.py huabc2 --measurement bind

Prerequisites (generated by analysis/prep_training_data.py):
    output/{protein}/{protein}_training_log2.csv
    output/{protein}/combo_muts.csv
    For single-chain: data/{protein}.fasta
    For HuABC2: data/huabc2_vh.fasta, data/huabc2_vl.fasta

    Optional: output/{protein}/{protein}[_multievolve_variants[_{measurement}]]_log2.csv
    (experimentally tested MULTI-evolve variants; also written by prep_training_data.py)

Output:
    output/{protein}/{protein}[_{measurement}]_multievolve_proposals.csv
    Columns: Mutations, Full_Sequence, Mut_string, num_muts, <fold_0..9>, average

    output/{protein}/{protein}[_{measurement}][_0layer]_multievolve_eval_predictions.csv
    Ensemble predictions (log2) for the training variants and the experimentally
    tested MULTI-evolve variants, with their measured values.
    Columns: mutation, set, num_muts, measured, <fold_0..9>, average (MinMax-scaled),
    average_log2 (inverse-transformed to the measured log2 scale)
    NOTE: 'train' rows are in-sample for the ensemble.
"""
import os
import sys

# Disable wandb (pulled in by MULTI-evolve internals but not used here)
os.environ['WANDB_MODE'] = 'disabled'

REPO = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'MULTI-evolve')
sys.path.insert(0, REPO)

import pandas as pd
from Bio import SeqIO

from multievolve.splitters import KFoldProteinSplitter
from multievolve.featurizers import OneHotFeaturizer
from multievolve.predictors import Fcn
from multievolve.proposers import CombinatorialProposer

import argparse
import hashlib


# FCN configs keyed by (protein, measurement, zerolayer). measurement is None except for huabc2.
CONFIGS = {
    ('apex',   None,   False): dict(layer_size=100, num_layers=5, learning_rate=0.001,  batch_size=16, optimizer='adam', epochs=300),
    ('apex',   None,   True):  dict(layer_size=100, num_layers=0, learning_rate=0.001,  batch_size=32, optimizer='adam', epochs=300),
    ('dcasrx', None,   False): dict(layer_size=100, num_layers=1, learning_rate=0.001,  batch_size=32, optimizer='adam', epochs=300),
    ('dcasrx', None,   True):  dict(layer_size=100, num_layers=0, learning_rate=0.0001, batch_size=8,  optimizer='adam', epochs=300),
    ('huabc2', 'expr', False): dict(layer_size=100, num_layers=5, learning_rate=0.0001, batch_size=4,  optimizer='adam', epochs=300),
    ('huabc2', 'bind', False): dict(layer_size=100, num_layers=3, learning_rate=0.0001, batch_size=4,  optimizer='adam', epochs=300),
    ('huabc2', 'expr', True):  dict(layer_size=100, num_layers=0, learning_rate=0.001,  batch_size=16, optimizer='adam', epochs=300),
    ('huabc2', 'bind', True):  dict(layer_size=100, num_layers=0, learning_rate=0.0001, batch_size=4,  optimizer='adam', epochs=300),
}


def get_config(protein, measurement=None, zerolayer=False):
    """FCN config used by this script for the given protein / measurement / layer setting."""
    key = (protein, measurement if protein == 'huabc2' else None, zerolayer)
    if key not in CONFIGS:
        raise KeyError(f"No config for protein={protein!r}, measurement={measurement!r}, zerolayer={zerolayer}")
    return dict(CONFIGS[key])


def hashed_training_csv(training_csv):
    """Path of the content-hashed copy of `training_csv` that the models are trained from.

    MULTI-evolve caches splits/models by training-CSV *filename*, so a stale cache
    silently overrides an updated CSV (e.g. one cached before A134P was excluded).
    Training from a content-hashed copy makes the cache key change whenever the data does.
    """
    with open(training_csv, 'rb') as f:
        digest = hashlib.md5(f.read()).hexdigest()[:8]
    return training_csv.replace('.csv', f'_{digest}.csv')


def cached_model_paths(protein, training_csv, config, n_splits=10, measurement=None):
    """Cached FCN checkpoint for each fold, as trained by this script on `training_csv` with `config`.

    Only returns the exact models (current training-data hash, architecture, learning rate,
    batch size, optimizer). Raises FileNotFoundError if any fold is missing, instead of
    falling back to whatever other models happen to be in the cache.
    """
    dataset_name = os.path.splitext(os.path.basename(hashed_training_csv(training_csv)))[0]
    objects_dir = os.path.join(REPO, 'proteins', protein, 'model_cache', dataset_name, 'objects')
    arch = '-'.join([str(config['layer_size'])] * config['num_layers'])
    suffix = (f" __ onehot __ fcn __ {arch} __ {config['learning_rate']}"
              f" __ {config['batch_size']} __ {config['optimizer']}.pth")
    rerun_hint = (f"Train them with: python analysis/run_multievolve.py {protein}"
                  + (f" --measurement {measurement or '<expr|bind>'}" if protein == 'huabc2' else "")
                  + (" --zerolayer" if config['num_layers'] == 0 else ""))

    if not os.path.isdir(objects_dir):
        raise FileNotFoundError(
            f"No model cache for the current training data ({os.path.basename(training_csv)}):\n"
            f"  {objects_dir}\n"
            "The training CSV has changed since the models were trained, or they were never trained.\n"
            + rerun_hint)
    files = os.listdir(objects_dir)
    paths = []
    for i in range(n_splits):
        matches = [f for f in files if f.startswith(f'split_by_kfold-{i}_') and f.endswith(suffix)]
        if len(matches) != 1:
            raise FileNotFoundError(
                f"Expected exactly 1 cached model for fold {i} matching '*{suffix}' "
                f"in {objects_dir}, found {len(matches)}: {matches}\n" + rerun_hint)
        paths.append(os.path.join(objects_dir, matches[0]))
    return paths


if __name__ == '__main__':
    # Required on macOS: multiprocessing uses 'spawn' so all executable code
    # must be inside this guard to prevent infinite re-execution of the script.
    parser = argparse.ArgumentParser()
    parser.add_argument('protein', type=str, choices=['apex', 'dcasrx', 'huabc2'])
    parser.add_argument('--zerolayer', action='store_true', help="Use 0-layer NN (instead of default architecture)")
    parser.add_argument('--measurement', type=str, default=None,
                        choices=['expr', 'bind'],
                        help='Measurement type (required for huabc2)')
    args = parser.parse_args()

    if args.protein == 'huabc2' and args.measurement is None:
        parser.error('--measurement is required for huabc2')

    # ---- Architecture ----
    CONFIG = get_config(args.protein, args.measurement, args.zerolayer)

    # ---- Paths ----
    ANALYSIS_DIR = os.path.dirname(os.path.abspath(__file__))
    ROOT_DIR     = os.path.dirname(ANALYSIS_DIR)
    # Training data written by prep_training_data.py
    PROTEINS_DIR = os.path.join(ROOT_DIR, 'output', args.protein)

    meas_tag = f'_{args.measurement}' if args.measurement else ''

    if args.protein == 'huabc2':
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'huabc2_training_{args.measurement}_log2.csv')
        # Multi-chain: pass list of FASTA files (VH, VL)
        DATA_DIR = os.path.join(ROOT_DIR, 'data')
        WT_FASTA = [
            os.path.join(DATA_DIR, 'huabc2_vh.fasta'),
            os.path.join(DATA_DIR, 'huabc2_vl.fasta'),
        ]
        IS_MULTICHAIN = True
    else:
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'{args.protein}_training_log2.csv')
        WT_FASTA     = os.path.join(ROOT_DIR, 'data', f'{args.protein}.fasta')
        IS_MULTICHAIN = False

    layer_tag = '_0layer' if args.zerolayer else ''
    OUTPUT_CSV = os.path.join(
        PROTEINS_DIR, f'{args.protein}{meas_tag}{layer_tag}_multievolve_proposals.csv')
    COMBO_CSV  = os.path.join(PROTEINS_DIR, 'combo_muts.csv')

    # KFoldProteinSplitter resolves paths relative to the MULTI-evolve repo root
    # So wt_file and data must be absolute paths
    paths_to_check = [TRAINING_CSV, COMBO_CSV]
    if IS_MULTICHAIN:
        paths_to_check.extend(WT_FASTA)
    else:
        paths_to_check.append(WT_FASTA)
    for path in paths_to_check:
        if not os.path.exists(path):
            raise FileNotFoundError(
                f"Missing: {path}\n"
                "Run: python analysis/prep_training_data.py "
                f"{args.protein}"
            )

    # Train from a content-hashed copy (see hashed_training_csv) so a stale cache can't be reused.
    import shutil
    _hashed_csv = hashed_training_csv(TRAINING_CSV)
    shutil.copyfile(TRAINING_CSV, _hashed_csv)
    SPLITTER_CSV = _hashed_csv

    # ---- K-fold splits ----
    print("Generating 10-fold splits...")
    splitter = KFoldProteinSplitter(
        args.protein,
        SPLITTER_CSV,
        WT_FASTA,
        csv_has_header=True,
        use_cache=True,
        y_scaling=True,
        val_split=0.15,
    )
    splits = splitter.generate_splits(n_splits=10)
    print(f"  Training set size: {len(splitter.data)} variants")

    # ---- Train 10 FCN models ----
    print("Training 10 FCN models (one per fold)...")
    featurizer = OneHotFeaturizer(protein=args.protein, use_cache=True)
    models = []
    for i, split in enumerate(splits):
        print(f"  Fold {i+1}/10...", flush=True)
        model = Fcn(split, featurizer, config=CONFIG, use_cache=True, show_plots=False)
        model.run_model()
        models.append(model)
    print("Training complete.")

    # ---- Load WT sequence and mutation pool ----
    if IS_MULTICHAIN:
        # Concatenate chain sequences
        chain_seqs = []
        for fasta_path in WT_FASTA:
            chain_seqs.append(str(SeqIO.read(fasta_path, 'fasta').seq.upper()))
        wt_seq = ''.join(chain_seqs)
        chain_lengths = [len(s) for s in chain_seqs]
        print(f"Multi-chain WT: {' + '.join(str(l) for l in chain_lengths)} "
              f"= {len(wt_seq)} AA")

        # Convert chain-notation combo_muts (e.g. 'L11Q:WT', 'WT:F82G')
        # to flat format with VL positions offset by VH chain length.
        # This matches what _shift_mutation_position() does for training data.
        raw_muts = pd.read_csv(COMBO_CSV, header=None)[0].tolist()
        mutation_pool = []
        for entry in raw_muts:
            parts = entry.split(':')
            # Chain 1 (VH) mutations — positions unchanged
            for m in parts[0].split('/'):
                if m != 'WT':
                    mutation_pool.append(m)
            # Chain 2 (VL) mutations — offset positions by chain 1 length
            for m in parts[1].split('/'):
                if m != 'WT':
                    wt_aa = m[0]
                    pos = int(m[1:-1])
                    mut_aa = m[-1]
                    offset_pos = pos + chain_lengths[0]
                    mutation_pool.append(f'{wt_aa}{offset_pos}{mut_aa}')
    else:
        wt_seq = str(SeqIO.read(WT_FASTA, 'fasta').seq.upper())
        mutation_pool = pd.read_csv(COMBO_CSV, header=None).values.flatten().tolist()

    print(f"Mutation pool: {len(mutation_pool)} mutations — {mutation_pool}")

    # ---- Generate and score all combinatorial variants ----
    # trust_radius=9 generates r=2..9 mutations
    # num_seeds=-1 enumerates all combinations
    print("Generating all combinatorial proposals (trust_radius=9)...")
    proposer = CombinatorialProposer(
        start_seq=wt_seq,
        models=models,
        trust_radius=9,
        num_seeds=-1,
        mutation_pool=mutation_pool,
    )
    proposer.propose(output_df=False)
    print(f"  Generated {len(proposer.proposals)} combinatorial variants")

    print("Scoring with ensemble models...")
    proposer.evaluate_proposals()

    print(f"\nTotal proposals scored: {len(proposer.proposals)}")
    print(proposer.proposals[['Mut_string', 'num_muts', 'average']].head(10))

    proposer.proposals.to_csv(OUTPUT_CSV, index=False)
    print(f"\nSaved to {OUTPUT_CSV}")

    # ---- Score the training variants and experimentally tested MULTI-evolve variants ----
    if IS_MULTICHAIN:
        chain_offsets = [0, chain_lengths[0]]

    def mutation_to_full_seq(mut_str):
        """Apply a dataset mutation string ('A/B' or 'A/B:C' for multi-chain) to WT."""
        chains = mut_str.split(':') if IS_MULTICHAIN else [mut_str]
        seq = list(wt_seq)
        n = 0
        for chain_idx, chain_str in enumerate(chains):
            offset = chain_offsets[chain_idx] if IS_MULTICHAIN else 0
            for m in chain_str.split('/'):
                if m == 'WT':
                    continue
                wt_aa, pos, mut_aa = m[0], int(m[1:-1]) + offset, m[-1]
                assert seq[pos - 1] == wt_aa, f"{m}: WT has {seq[pos - 1]} at {pos}"
                seq[pos - 1] = mut_aa
                n += 1
        return ''.join(seq), n

    if args.protein == 'huabc2':
        MULTI_CSV = os.path.join(
            PROTEINS_DIR, f'huabc2_multievolve_variants_{args.measurement}_log2.csv')
    else:
        MULTI_CSV = os.path.join(
            PROTEINS_DIR, f'{args.protein}_multievolve_variants_log2.csv')
    if not os.path.exists(MULTI_CSV):
        raise FileNotFoundError(
            f"Missing: {MULTI_CSV}\n"
            f"Run: python analysis/prep_training_data.py {args.protein}")

    train_eval = pd.read_csv(TRAINING_CSV)
    train_eval = train_eval[~train_eval['mutation'].isin(['WT', 'WT:WT'])]
    train_eval = train_eval[['mutation', 'property_value']].assign(set='train')
    multi_eval = pd.read_csv(MULTI_CSV).assign(set='multievolve_variant')
    eval_df = pd.concat([train_eval, multi_eval], ignore_index=True)
    eval_df = eval_df.rename(columns={'property_value': 'measured'})

    built = eval_df['mutation'].apply(mutation_to_full_seq)
    eval_df['Full_Sequence'] = built.str[0]
    eval_df['num_muts'] = built.str[1]
    for model in models:
        name = model.file_attrs['model_name']
        eval_df[name] = model.predict(eval_df['Full_Sequence'])
    eval_df['average'] = eval_df.iloc[:, -len(models):].mean(axis=1)
    # Model outputs are on the MinMax-scaled [0, 1] axis (y_scaling=True; the scaler
    # is fit on every row of the training CSV, WT included). Invert to log2 units.
    y_all = pd.read_csv(TRAINING_CSV)['property_value']
    eval_df['average_log2'] = eval_df['average'] * (y_all.max() - y_all.min()) + y_all.min()

    EVAL_CSV = os.path.join(
        PROTEINS_DIR,
        f'{args.protein}{meas_tag}{layer_tag}_multievolve_eval_predictions.csv')
    eval_df.drop(columns=['Full_Sequence']).to_csv(EVAL_CSV, index=False)
    print(f"Saved {len(eval_df)} evaluation predictions to {EVAL_CSV}")
