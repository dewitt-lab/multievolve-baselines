#!/usr/bin/env python
"""
Hyperparameter sweep for MULTI-evolve FCN on APEX, dCasRx, or HuABC2 data.

Run from the project root with the multievolve conda environment:
    conda activate multievolve
    python analysis/multievolve_hyperparameter_sweep.py apex
    python analysis/multievolve_hyperparameter_sweep.py dcasrx
    python analysis/multievolve_hyperparameter_sweep.py huabc2 --measurement expr
    python analysis/multievolve_hyperparameter_sweep.py huabc2 --measurement bind

Prerequisites (generated by analysis/prep_training_data.py):
    output/{protein}/{protein}_training_log2.csv
    For HuABC2: output/huabc2/huabc2_training_{expr,bind}_log2.csv
"""
import os
import sys

# Disable wandb (pulled in by MULTI-evolve internals but not used here)
os.environ['WANDB_MODE'] = 'disabled'

REPO = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'MULTI-evolve')
sys.path.insert(0, REPO)

import numpy as np
import pandas as pd
from Bio import SeqIO
from scipy.stats import spearmanr as _spearmanr
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error

from multievolve.splitters import KFoldProteinSplitter
from multievolve.featurizers import OneHotFeaturizer
from multievolve.predictors import Fcn
from multievolve.proposers import CombinatorialProposer

import argparse




CONFIG_SWEEP = {
    'layer_size': [100],
    'num_layers': [0, 1, 2, 3, 4, 5],
    'learning_rate': [0.0001, 0.001, 0.01],
    'batch_size': [4, 8, 16, 32],
    'optimizer': ['adam'],
    'epochs': [300],
}

# CONFIG_SWEEP = {
#     'layer_size': [100],
#     'num_layers': [1, 2],
#     'learning_rate': [0.0001, 0.001, 0.01],
#     'batch_size': [4, 32],
#     'optimizer': ['adam'],
#     'epochs': [300],
# }


from itertools import product

def next_config():
    hparam_names = list(CONFIG_SWEEP.keys())

    hparam_lists = [CONFIG_SWEEP[hparam] for hparam in hparam_names]

    for combo in product(*hparam_lists):
        config = {hparam: val for hparam, val in zip(hparam_names, combo)}
        yield config




if __name__ == '__main__':
    # Required on macOS: multiprocessing uses 'spawn' so all executable code
    # must be inside this guard to prevent infinite re-execution of the script.
    parser = argparse.ArgumentParser()
    parser.add_argument('protein', type=str, choices=['apex', 'dcasrx', 'huabc2'])
    parser.add_argument('--measurement', type=str, default=None,
                        choices=['expr', 'bind'],
                        help='Measurement type (required for huabc2)')
    args = parser.parse_args()

    if args.protein == 'huabc2' and args.measurement is None:
        parser.error('--measurement is required for huabc2')

    # ---- Paths ----
    ANALYSIS_DIR = os.path.dirname(os.path.abspath(__file__))
    ROOT_DIR     = os.path.dirname(ANALYSIS_DIR)
    # Training data written by prep_training_data.py
    PROTEINS_DIR = os.path.join(ROOT_DIR, 'output', args.protein)

    if args.protein == 'huabc2':
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'huabc2_training_{args.measurement}_log2.csv')
        # Multi-chain: pass list of FASTA files (VH, VL)
        DATA_DIR = os.path.join(ROOT_DIR, 'data')
        WT_FASTA = [
            os.path.join(DATA_DIR, 'huabc2_vh.fasta'),
            os.path.join(DATA_DIR, 'huabc2_vl.fasta'),
        ]
    else:
        TRAINING_CSV = os.path.join(
            PROTEINS_DIR, f'{args.protein}_training_log2.csv')
        WT_FASTA = os.path.join(ROOT_DIR, 'data', f'{args.protein}.fasta')

    # KFoldProteinSplitter resolves paths relative to the MULTI-evolve repo root
    # (root_folder = dirname(dirname(dirname(base_splitters.py))) = REPO)
    # So wt_file and data must be absolute paths
    if not os.path.exists(TRAINING_CSV):
        raise FileNotFoundError(
            f"Missing: {TRAINING_CSV}\n"
            "Run: python analysis/prep_training_data.py {args.protein}")

    # ---- K-fold splits ----
    print("Generating 5-fold splits...")
    splitter = KFoldProteinSplitter(
        args.protein,
        TRAINING_CSV,
        WT_FASTA,
        csv_has_header=True,
        use_cache=True,
        y_scaling=True,
        val_split=0.15,
    )
    splits = splitter.generate_splits(n_splits=5)
    print(f"  Training set size: {len(splitter.data)} variants")

    results_list = []

    for config in next_config():
        print(config)

        # ---- Train 5 FCN models ----
        featurizer = OneHotFeaturizer(protein=args.protein, use_cache=True)
        log10_mse_list = []
        spearmanr_list = []
        for i, split in enumerate(splits):
            model = Fcn(split, featurizer, config=config, use_cache=False, show_plots=False)
            stats = model.run_model()
            log10_mse_list.append(np.log10(stats['MSE']))
            spearmanr_list.append(stats["Spearman r"])
        
        log10_mse = np.mean(log10_mse_list)
        spearmanr = np.mean(spearmanr_list)

        print(log10_mse_list)
        print(spearmanr_list)

        results = {
            'config': config,
            'log10_mse': log10_mse,
            'spearmanr': spearmanr,
        }
        results_list.append(results)

    # ---- Closed-form OLS ----
    print("Training OLS (closed-form) on same splits...")
    featurizer = OneHotFeaturizer(protein=args.protein, use_cache=True)
    log10_mse_list = []
    spearmanr_list = []
    for i, split in enumerate(splits):
        # Featurize train and test sequences
        X_train = featurizer.featurize(split.splits['X_train'])
        X_test = featurizer.featurize(split.splits['X_test'])
        y_train = np.array(split.splits['y_train'])
        y_test = np.array(split.splits['y_test'])

        # Flatten one-hot features to 2D
        X_train = X_train.reshape(X_train.shape[0], -1)
        X_test = X_test.reshape(X_test.shape[0], -1)

        ols = LinearRegression()
        ols.fit(X_train, y_train)
        y_pred = ols.predict(X_test)

        mse = mean_squared_error(y_test, y_pred)
        sr, _ = _spearmanr(y_test, y_pred)
        log10_mse_list.append(np.log10(mse))
        spearmanr_list.append(sr)

    log10_mse = np.mean(log10_mse_list)
    sr_mean = np.mean(spearmanr_list)
    print(f"  OLS log10(MSE) = {log10_mse:.4f}, Spearman r = {sr_mean:.4f}")

    ols_config = {
        'layer_size': 0,
        'num_layers': 'OLS',
        'learning_rate': 0,
        'batch_size': 0,
        'optimizer': 'OLS',
        'epochs': 0,
    }
    results_list.append({
        'config': ols_config,
        'log10_mse': log10_mse,
        'spearmanr': sr_mean,
    })

    import json

    meas_tag = f'_{args.measurement}' if args.measurement else ''
    out_file = os.path.join(
        PROTEINS_DIR, f'{args.protein}{meas_tag}_log2_hparams_results.jsonl')
    with open(out_file, "w+") as f:
        for d in results_list:
            f.write(json.dumps(d) + "\n")
    print(f"Wrote results to {out_file}")

